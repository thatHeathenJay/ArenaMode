"""Generates Generated.cs: stub declarations for every public TMPro type of the EFT client TextMeshPro DLL,
so AssetRipper can resolve any TMPro reference while ripping Arena. Types hand-written in Tmp.cs (the Unity 6
text layout) are skipped. Field layouts for the generated types are the EFT ones; where Arena differs AssetRipper
logs a mismatch and continues, which is fine for non-text widgets.

Usage: py gen_stubs.py <typedump.txt>   (typedump from tools/TypeDump on Unity.TextMeshPro.dll)
"""
import io, re, sys, collections

dump = sys.argv[1]
own = set(re.findall(r'\b(?:enum|struct|class)\s+([A-Za-z_][A-Za-z0-9_]*)', io.open('Tmp.cs', encoding='utf-8').read()))

PRIM = {'System.Int32': 'int', 'System.Single': 'float', 'System.Boolean': 'bool', 'System.String': 'string',
        'System.Char': 'char', 'System.Byte': 'byte', 'System.UInt32': 'uint', 'System.Int64': 'long',
        'System.UInt64': 'ulong', 'System.Double': 'double', 'System.Int16': 'short', 'System.UInt16': 'ushort',
        'System.Object': 'object', 'System.SByte': 'sbyte'}


def cs_type(t):
    t = t.strip()
    if t.endswith('[]'):
        return cs_type(t[:-2]) + '[]'
    m = re.match(r'^([A-Za-z0-9_.+]+)`(\d+)\[(.*)\]$', t)
    if m:
        args = [cs_type(strip_asm(a)) for a in split_args(m.group(3))]
        return cs_type(m.group(1)) + '<' + ', '.join(args) + '>'
    if t in PRIM:
        return PRIM[t]
    if t.startswith('TMPro.'):
        t = t[6:]
    return t.replace('+', '.')


def strip_asm(a):
    # Base types come assembly-qualified: [System.Int32, mscorlib, Version=...]; keep the type name only.
    a = a.strip()
    if a.startswith('['):
        a = a[1:-1] if a.endswith(']') else a[1:]
        a = a.split(',', 1)[0]
    return a


def split_args(s):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch == '[': depth += 1
        if ch == ']': depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur); cur = ''
        else:
            cur += ch
    if cur: out.append(cur)
    return out


rows = []
for line in io.open(dump, encoding='utf-8'):
    parts = line.rstrip('\n').split('|')
    if len(parts) < 5: continue
    kind, full, base, flags, fields = parts[0], parts[1], parts[2], parts[3], parts[4]
    rows.append((kind, full, base, flags, [f for f in fields.split(';') if f]))

children = collections.defaultdict(list)
roots = []
for r in rows:
    full = r[1]
    if '+' in full:
        children[full.rsplit('+', 1)[0]].append(r)
    else:
        roots.append(r)


def short(full):
    name = full.split('+')[-1].split('.')[-1]
    m = re.match(r'^(.*)`(\d+)$', name)
    if m:
        n = int(m.group(2))
        return m.group(1) + '<' + ', '.join('T' if n == 1 else f'T{i}' for i in range(n)) + '>'
    return name


def emit(r, indent):
    kind, full, base, flags, fields = r
    name = short(full)
    bare = name.split('<')[0]
    out = []
    pad = '    ' * indent
    if bare in own:
        return out
    if kind == 'enum':
        out.append(f'{pad}public enum {name} {{ }}')
        return out
    if kind == 'interface':
        out.append(f'{pad}public interface {name} {{ }}')
        return out
    if base == 'System.MulticastDelegate':
        out.append(f'{pad}public delegate void {name}();')
        return out
    if kind == 'struct':
        head = f'{pad}[System.Serializable] public struct {name}'
    else:
        b = ''
        if base and base not in ('System.Object',):
            b = ' : ' + cs_type(base)
        head = f'{pad}public {"abstract " if flags == "abstract" else ""}class {name}{b}'
    out.append(head)
    out.append(pad + '{')
    for f in fields:
        ftype, fname = f.rsplit(':', 1)
        out.append(f'{pad}    [UnityEngine.SerializeField] public {cs_type(ftype)} {fname};')
    for c in children.get(full, []):
        out += emit(c, indent + 1)
    out.append(pad + '}')
    return out


lines = ['// <auto-generated by gen_stubs.py; EFT TextMeshPro type surface for AssetRipper. Do not edit.>',
         '#pragma warning disable', 'using System.Collections.Generic;', 'using UnityEngine;', 'using UnityEngine.UI;',
         'using UnityEngine.Events;', 'using TMPro;']
by_ns = collections.defaultdict(list)
for r in roots:
    by_ns[r[1].rsplit('.', 1)[0]].append(r)
for ns in sorted(by_ns):
    lines += [f'namespace {ns}', '{']
    for r in by_ns[ns]:
        lines += emit(r, 1)
    lines.append('}')
io.open('Generated.cs', 'w', encoding='utf-8').write('\n'.join(lines) + '\n')
print('generated', sum(1 for r in rows if short(r[1]).split('<')[0] not in own), 'types')
